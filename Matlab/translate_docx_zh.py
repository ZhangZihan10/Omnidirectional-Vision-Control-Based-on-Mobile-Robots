def set_east_asia_font(run, font_name="Microsoft YaHei"):
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)


def replace_paragraph_text(paragraph, text):
    if paragraph.runs:
        first = paragraph.runs[0]
        first.text = text
        set_east_asia_font(first)
        for run in paragraph.runs[1:]:
            run.text = ""
            set_east_asia_font(run)
    else:
        run = paragraph.add_run(text)
        set_east_asia_font(run)


def main():
    doc = Document(SOURCE)
    non_empty = [p for p in doc.paragraphs if p.text.strip()]
    if len(non_empty) != len(TRANSLATIONS):
        raise RuntimeError(f"Expected {len(TRANSLATIONS)} text paragraphs, found {len(non_empty)}")

    for paragraph, translated in zip(non_empty, TRANSLATIONS):
        replace_paragraph_text(paragraph, translated)

    for style_name in ["Normal", "Heading 1", "Heading 2", "Heading 3"]:
        if style_name in doc.styles:
            style = doc.styles[style_name]
            style.font.name = "Microsoft YaHei"
            style._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
